#!/usr/bin/env python3
"""Counting reverse proxy: the independent record a run's ledger is checked against.

usage: python3 -I countproxy.py LISTEN_PORT TARGET_PORT LOG.jsonl

Forwards every request on 127.0.0.1:LISTEN_PORT to 127.0.0.1:TARGET_PORT and
appends one JSON line per request to LOG.jsonl: {"t": epoch, "method", "path"}
(path includes the query). Used as a forward proxy (azhaq -proxy, or Chrome
behind it), a request arrives with the full address; it is logged and sent to
the origin as its path and query, as any forward proxy does: an origin such as
Express cannot read a full address as a request target. Do not edit this file
to make a ledger match.
"""
import http.client
import json
import sys
import threading
import time
from urllib.parse import urlsplit
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

LISTEN, TARGET, LOG = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
lock = threading.Lock()


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def handle_one(self):
        length = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(length) if length else None
        path = self.path
        if not path.startswith("/") and path != "*":
            u = urlsplit(path)  # absolute-form, from a client that treats this as a proxy
            path = (u.path or "/") + ("?" + u.query if u.query else "")
        with lock, open(LOG, "a") as f:
            f.write(json.dumps({"t": time.time(), "method": self.command, "path": path}) + "\n")
        conn = http.client.HTTPConnection("127.0.0.1", TARGET, timeout=30)
        headers = {k: v for k, v in self.headers.items() if k.lower() not in ("connection", "keep-alive")}
        try:
            conn.request(self.command, path, body=body, headers=headers)
            resp = conn.getresponse()
            data = resp.read()
        except Exception as e:  # the target did not answer: say so, as a gateway would
            self.send_error(502, str(e))
            return
        self.send_response(resp.status, resp.reason)
        for k, v in resp.getheaders():
            if k.lower() not in ("transfer-encoding", "connection", "content-length"):
                self.send_header(k, v)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(data)

    do_GET = do_POST = do_PUT = do_PATCH = do_DELETE = do_HEAD = do_OPTIONS = handle_one

    def log_message(self, *args):
        pass


ThreadingHTTPServer(("127.0.0.1", LISTEN), Handler).serve_forever()
